/** MG-06 コーチングチーム MVP の headless 回帰。 */
'use strict';
const { makeLeagueContext } = require('./lib/league-context.js');
const c = makeLeagueContext();
const L = c.L;
const MY = 'england2026';
let pass = 0, fail = 0;
function check(name, cond) { if (cond) { pass++; console.log('  ✅ ' + name); } else { fail++; console.log('  ❌ ' + name); } }
console.log('\nMG-06 コーチングチーム');
L.newSeason(MY);
let state = L.getState();
check('新規キャリアに分析コーチとフィジカルコーチがいる', state.manager.coaches.analysis === 1 && state.manager.coaches.physical === 1);
state.manager.coaches.physical = 0;
c.ls.setItem(c.LS_KEY, JSON.stringify(state));
L.setState(null); L.load(); state = L.getState();
check('既存v4の未使用 physical=0 を標準スタッフへ補完する', state.manager.coaches.physical === 1);
check('補完結果が localStorage に保存される', JSON.parse(c.ls.getItem(c.LS_KEY)).manager.coaches.physical === 1);
c.win.LANG = 'ja'; let advice = L.physicalCoachAdvice(MY);
check('負傷者なしは日本語の良好レポート', advice.status === 'ready' && /懸念はありません/.test(advice.text));
c.win.LANG = 'en'; advice = L.physicalCoachAdvice(MY);
check('英語表示にも良好レポートがある', advice.status === 'ready' && /No fitness concerns/.test(advice.text));
const p = c.TEAM_DATA[MY].players[0];
L.squadEntry(MY, p.long_name || p.name).injuryOut = 2;
c.win.LANG = 'ja'; advice = L.physicalCoachAdvice(MY);
check('負傷者をコンディション不良として助言する', advice.status === 'concern' && advice.weeks === 2 && /回復日/.test(advice.text));
c.win.LANG = 'en'; advice = L.physicalCoachAdvice(MY);
check('負傷助言も英語を持つ', advice.status === 'concern' && /recovery day/.test(advice.text));
const myPlayer = { name: '自軍選手', en_name: 'Our Player' };
const oppPlayer = { name: '相手選手', en_name: 'Opponent' };
const myTeam = { players: [myPlayer], lineup: [0] };
const oppTeam = { players: [oppPlayer], lineup: [0] };
const completed = { scenes: [{ offence: myTeam, defence: oppTeam, ofsPos: 0, dfsPos: 0, action: 'ショートパス', result: '失敗', ofsPoint: 55, dfsPoint: 68 }] };
c.win.LANG = 'ja'; let card = L.analysisCoachCard('opponent_focus', oppPlayer, completed, myTeam);
check('不利な対面を自軍選手名つきで報告する', /自軍選手/.test(card.body) && /マッチアップ/.test(card.body));
c.win.LANG = 'en'; card = L.analysisCoachCard('opponent_focus', oppPlayer, completed, myTeam);
check('試合中レポートも英語を持つ', /Our Player/.test(card.body) && /unfavourable matchup/.test(card.body));
const even = { scenes: [{ offence: myTeam, defence: oppTeam, ofsPos: 0, dfsPos: 0, action: 'ショートパス', result: '失敗', ofsPoint: 65, dfsPoint: 66 }] };
card = L.analysisCoachCard('opponent_focus', oppPlayer, even, myTeam);
check('明確な不利がなければ相手の攻撃起点を報告する', /Opponent/.test(card.body));
console.log('\n' + pass + ' passed, ' + fail + ' failed');
if (fail) process.exit(1);
